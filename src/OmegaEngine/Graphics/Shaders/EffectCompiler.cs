using System;
using System.Collections.Generic;
using System.Text;
using OmegaEngine.D3DX;
using SharpGen.Runtime;
using Vortice.Direct3D;

namespace OmegaEngine.Graphics.Shaders;

/// <summary>
/// Compiles <c>.fx</c> source code to effect bytecode.
/// </summary>
internal static class EffectCompiler
{
    /// <summary>
    /// The DLL containing the compiler. Its version determines the generated bytecode.
    /// </summary>
    public const string DllName = "d3dcompiler_47.dll";

    /// <summary>
    /// Compiles <c>.fx</c> source code to bytecode that can be loaded with <see cref="Effect.FromMemory"/>.
    /// </summary>
    /// <param name="source">The HLSL source code of the effect.</param>
    /// <param name="defines">Preprocessor macros.</param>
    /// <param name="flags">Compile options.</param>
    /// <exception cref="SharpGenException">The effect could not be compiled. The message contains the compiler output.</exception>
    public static byte[] Compile(string source, IEnumerable<ShaderMacro>? defines = null, ShaderFlags flags = ShaderFlags.None)
    {
        #region Sanity checks
        if (source == null) throw new ArgumentNullException(nameof(source));
        #endregion

        var result = Vortice.D3DCompiler.Compiler.Compile(
            Encoding.UTF8.GetBytes(source),
            [..defines ?? [], default], // Terminated by an empty entry
            include: null!, entryPoint: null!, sourceName: null!, profile: "fx_2_0",
            (Vortice.D3DCompiler.ShaderFlags)flags, Vortice.D3DCompiler.EffectFlags.None,
            out var effect, out var errors);
        using (effect)
        using (errors)
        {
            // Successful compiles still report warnings, including one about effects being deprecated
            if (result.Failure) throw new SharpGenException(result, errors?.AsString());
            return effect.AsBytes();
        }
    }
}
